install_zed() {
    mkdir -p "$zed_config_dir"

    if [ -f "$zed_settings_target" ] && [ "$(head -n 1 "$zed_settings_target")" = "$zed_settings_marker" ]; then
        :
    elif [ -e "$zed_settings_backup" ] || [ -L "$zed_settings_backup" ]; then
        printf 'Cannot install Zed settings: backup already exists at %s\n' "$zed_settings_backup" >&2
        exit 1
    elif [ -e "$zed_settings_target" ] || [ -L "$zed_settings_target" ]; then
        mv "$zed_settings_target" "$zed_settings_backup"
        printf 'Backed up existing Zed settings to %s\n' "$zed_settings_backup"
    fi

    if ! command -v jq >/dev/null 2>&1; then
        printf 'jq is required to merge Zed settings. Run: brew bundle --file "%s/Brewfile"\n' "$repo_dir" >&2
        exit 1
    fi

    zed_tmp_base=$(mktemp "${TMPDIR:-/tmp}/dotfiles-zed-base.XXXXXX")
    grep -v '^[[:space:]]*//' "$zed_settings_source" > "$zed_tmp_base"

    zed_tmp_overlay=$(mktemp "${TMPDIR:-/tmp}/dotfiles-zed-overlay.XXXXXX")
    if [ -f "$zed_settings_local" ]; then
        grep -v '^[[:space:]]*//' "$zed_settings_local" > "$zed_tmp_overlay"
    else
        printf '{}' > "$zed_tmp_overlay"
    fi

    {
        printf '%s\n' "$zed_settings_marker"
        jq -s '.[0] * .[1]' "$zed_tmp_base" "$zed_tmp_overlay"
    } > "$zed_settings_target"
    rm -f "$zed_tmp_base" "$zed_tmp_overlay"
    printf 'Generated Zed settings at %s\n' "$zed_settings_target"

    if [ -L "$zed_agents_target" ] && [ "$(readlink "$zed_agents_target")" = "$zed_agents_source" ]; then
        printf 'Zed AGENTS.md is already installed.\n'
    else
        if [ -e "$zed_agents_backup" ] || [ -L "$zed_agents_backup" ]; then
            printf 'Cannot install Zed AGENTS.md: backup already exists at %s\n' "$zed_agents_backup" >&2
            exit 1
        fi

        if [ -e "$zed_agents_target" ] || [ -L "$zed_agents_target" ]; then
            mv "$zed_agents_target" "$zed_agents_backup"
            printf 'Backed up existing Zed AGENTS.md to %s\n' "$zed_agents_backup"
        fi

        ln -s "$zed_agents_source" "$zed_agents_target"
        printf 'Linked Zed AGENTS.md at %s\n' "$zed_agents_target"
    fi

    if ! command -v zed >/dev/null 2>&1; then
        if [ "$(uname)" = "Darwin" ]; then
            printf 'Zed is not installed. Run: brew bundle --file "%s/Brewfile"\n' "$repo_dir"
        else
            printf 'Zed is not installed. Install it from https://zed.dev/download\n'
        fi
    fi
}

