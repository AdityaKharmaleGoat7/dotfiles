# Links a single source path to a single target path, backing up anything
# already at the target. Used for Codex's AGENTS.md plus its per-file
# rules/ and per-directory skills/ entries, which are too numerous to give
# each its own hand-written install_<name>/uninstall_<name> pair.
# $1 = source path, $2 = target path, $3 = label for log messages
install_codex_link() {
    if [ -L "$2" ] && [ "$(readlink "$2")" = "$1" ]; then
        printf '%s is already installed.\n' "$3"
        return
    fi

    if [ -e "$2.pre-dotfiles" ] || [ -L "$2.pre-dotfiles" ]; then
        printf 'Cannot install %s: backup already exists at %s\n' "$3" "$2.pre-dotfiles" >&2
        exit 1
    fi

    if [ -e "$2" ] || [ -L "$2" ]; then
        mv "$2" "$2.pre-dotfiles"
        printf 'Backed up existing %s to %s\n' "$3" "$2.pre-dotfiles"
    fi

    ln -s "$1" "$2"
    printf 'Linked %s at %s\n' "$3" "$2"
}

uninstall_codex_link() {
    if [ -L "$2" ] && [ "$(readlink "$2")" = "$1" ]; then
        unlink "$2"
        printf 'Removed %s link at %s\n' "$3" "$2"

        if [ -e "$2.pre-dotfiles" ] || [ -L "$2.pre-dotfiles" ]; then
            mv "$2.pre-dotfiles" "$2"
            printf 'Restored previous %s.\n' "$3"
        fi
    else
        printf 'No managed %s link found.\n' "$3"
    fi
}

install_codex() {
    mkdir -p "$codex_dir" "$codex_dir/rules" "$codex_dir/skills"

    install_codex_link "$codex_source" "$codex_target" "Codex AGENTS.md"

    for rules_file in "$repo_dir"/config/codex/rules/*.rules; do
        [ -e "$rules_file" ] || continue
        rules_name=$(basename "$rules_file")
        install_codex_link "$rules_file" "$codex_dir/rules/$rules_name" "Codex rule ($rules_name)"
    done

    for skill_dir in "$repo_dir"/config/codex/skills/*; do
        [ -d "$skill_dir" ] || continue
        skill_name=$(basename "$skill_dir")
        install_codex_link "$skill_dir" "$codex_dir/skills/$skill_name" "Codex skill ($skill_name)"
    done
}

uninstall_codex() {
    uninstall_codex_link "$codex_source" "$codex_target" "Codex AGENTS.md"

    for rules_file in "$repo_dir"/config/codex/rules/*.rules; do
        [ -e "$rules_file" ] || continue
        rules_name=$(basename "$rules_file")
        uninstall_codex_link "$rules_file" "$codex_dir/rules/$rules_name" "Codex rule ($rules_name)"
    done

    for skill_dir in "$repo_dir"/config/codex/skills/*; do
        [ -d "$skill_dir" ] || continue
        skill_name=$(basename "$skill_dir")
        uninstall_codex_link "$skill_dir" "$codex_dir/skills/$skill_name" "Codex skill ($skill_name)"
    done
}

install_dotfiles() {
    install_packages
    install_shell_config

    if git config --global --get-all include.path 2>/dev/null | grep -Fxq "$legacy_git_config"; then
        git config --global --fixed-value --unset-all include.path "$legacy_git_config"
        printf 'Removed obsolete Git include for %s\n' "$legacy_git_config"
    fi

    if git config --global --get-all include.path 2>/dev/null | grep -Fxq "$git_config"; then
        printf 'Git configuration is already installed.\n'
    else
        git config --global --add include.path "$git_config"
        printf 'Added Git include for %s\n' "$git_config"
    fi

    install_starship
    install_btop
    install_tmux
    install_zed
    install_lazygit
    install_codex
}

uninstall_dotfiles() {
    if [ -f "$zshrc_path" ] && grep -Fq "$start_marker" "$zshrc_path"; then
        temp_file=$(mktemp "${TMPDIR:-/tmp}/dotfiles-zshrc.XXXXXX")
        awk -v start="$start_marker" -v end="$end_marker" '
            $0 == start { skipping = 1; next }
            $0 == end { skipping = 0; next }
            !skipping { print }
        ' "$zshrc_path" > "$temp_file"
        mv "$temp_file" "$zshrc_path"
        printf 'Removed dotfiles loader from %s\n' "$zshrc_path"
    else
        printf 'No dotfiles loader found in %s.\n' "$zshrc_path"
    fi

    git config --global --fixed-value --unset-all include.path "$git_config" 2>/dev/null || true
    git config --global --fixed-value --unset-all include.path "$legacy_git_config" 2>/dev/null || true
    printf 'Removed Git include for %s, if it was present.\n' "$git_config"

    uninstall_starship
    uninstall_btop
    uninstall_tmux
    uninstall_zed
    uninstall_lazygit
    uninstall_codex
}

case "${1:-}" in
    "") install_dotfiles ;;
    --uninstall) uninstall_dotfiles ;;
    *)
        printf 'Usage: %s [--uninstall]\n' "$0" >&2
        exit 2
        ;;
esac
